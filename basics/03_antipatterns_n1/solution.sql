-- ---- 課題1: N+1問題 ----
-- 実測値の例（環境により変動するが、桁が変わるほどの差になる）:
--   ループで100回個別クエリ  : 約88秒
--   1回のクエリにまとめる    : 約0.9秒
--
-- なぜここまで差が出るのか:
--   個々のSQL自体は速くても、クエリを発行するたびに
--   「ネットワーク往復（ラウンドトリップ）」「コネクション処理」「パース」
--   といった固定のオーバーヘッドがかかる。これが100回分積み重なる。
--   1回のクエリにまとめれば、このオーバーヘッドは1回分で済む。
--
-- 実務での対策:
--   - JOIN で必要なデータを1回のクエリで取得する
--   - IN句でまとめて取得する（ORMのeager loading機能もこの仕組みを使っている）
SELECT * FROM order_items WHERE order_id IN (1,2,3,4,5 /* ... */);


-- ---- 課題2: 先頭ワイルドカードLIKE ----
EXPLAIN SELECT * FROM users WHERE email LIKE 'user012345%';
-- => type: range, key: idx_users_email, rows: 少数
-- 前方一致はB-Treeのソート順と相性が良く、インデックスの範囲検索が使える。

EXPLAIN SELECT * FROM users WHERE email LIKE '%johndoe@example.com';
-- => type: ALL, key: NULL, rows: 全行
-- 先頭が「%」だと「どこから始まるか」が分からないため、
-- ソート済みインデックスを辿る手段がなく、フルスキャンになる。
--
-- 対策: 前方一致で検索できるように要件を見直す、全文検索(FULLTEXT)や
-- 検索エンジン(Elasticsearch等)の利用を検討する。


-- ---- 課題3: インデックス列に関数をかけてしまう ----
EXPLAIN SELECT * FROM orders WHERE YEAR(created_at) = 2024 AND MONTH(created_at) = 6;
-- => type: ALL, key: NULL, rows: 全行(約498,000)
-- created_at にインデックスがあっても、列に YEAR()/MONTH() という関数を
-- かけてしまうと「インデックスに入っている値」と「関数を通した後の値」が
-- 一致しなくなるため、MySQLはインデックスを使えず全行スキャンになる。

EXPLAIN SELECT * FROM orders WHERE created_at >= '2024-06-01' AND created_at < '2024-07-01';
-- => type: range, key: idx_orders_created_at, rows: 約38,000
-- 同じ「2024年6月」を絞り込んでいるのに、列そのものを範囲比較する書き方に
-- 変えるだけでインデックスが使われるようになる。
--
-- 教訓: WHERE句のインデックス対象列には関数をかけない。
-- 日付の年月検索は「範囲条件」に書き換えるのが定石。


-- ---- 課題4: SELECT * の問題 ----
-- EXPLAIN上の type/rows は SELECT * でも SELECT id, status でも
-- 大きくは変わらないことが多いが（アクセス方法自体は同じ）、
-- 実際には SELECT * は以下のコストを持つ:
--   - 不要な列（TEXT型のcommentなど）まで転送し、ネットワーク帯域を消費する
--   - Stage 4で扱う「カバリングインデックス」の恩恵を受けられなくなる
