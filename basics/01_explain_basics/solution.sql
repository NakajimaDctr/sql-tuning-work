-- Stage 1: EXPLAINの読み方 - 解答（実行結果と解釈）
--
-- 実際の値はデータ生成の乱数により多少前後することがあるが、
-- type と Extra の傾向は再現される。
-- ============================================================

-- Q1. EXPLAIN SELECT * FROM users WHERE id = 100;
-- => type: const, key: PRIMARY, rows: 1
-- 主キーでの一意検索は最速の part。「値が1件に確定する」ため type=const になる。

-- Q2. EXPLAIN SELECT * FROM orders WHERE user_id = 100;
-- => type: ALL, key: NULL, rows: 約498,000（全行に近い数）
-- user_id にインデックスがないため、全行を1件ずつ確認するフルテーブルスキャンになる。
-- rows はテーブルの全行数とほぼ一致する = 「全部見ている」ことを意味する。

-- Q3. EXPLAIN SELECT * FROM users WHERE email = 'user012345.johndoe@example.com';
-- => type: ALL, key: NULL, rows: 約48,000（全行に近い数）
-- Q2と同様、email にインデックスがないためフルスキャン。
-- 「1件しかヒットしないはずの検索」でも、インデックスがなければ全件確認が必要になる
-- という点が重要（結果件数の少なさとスキャン量は無関係）。

-- Q4. EXPLAIN SELECT * FROM products WHERE category_id = 5 AND price > 1000;
-- => type: ALL, key: NULL, rows: 約10,000（全行）, Extra: Using where
-- 条件が2つあっても、どちらの列にもインデックスがなければ全行スキャンになる。
-- 「Using where」は「ストレージエンジンから受け取った行に対して、
-- サーバー側でさらにWHERE条件をふるいにかけた」ことを示す。

-- ------------------------------------------------------------
-- 主要カラムのまとめ
-- ------------------------------------------------------------
-- type (アクセス方法。左ほど速い/効率的)
--   system/const > eq_ref > ref > range > index > ALL
--   - const  : 主キー/ユニークキーで1行に確定する検索
--   - ref    : 非ユニークインデックスでの等値検索（複数行ヒットしうる）
--   - range  : インデックスを使った範囲検索（BETWEEN, <, >, IN等）
--   - index  : インデックス全体を走査（フルスキャンよりはマシだが行数分読む）
--   - ALL    : フルテーブルスキャン（インデックスを一切使わない）
--
-- rows      : オプティマイザが「このステップで読むと見積もった行数」の概算値
--             実際の行数と完全一致するとは限らない（Stage 5で詳しく扱う）
--
-- key       : 実際に使われたインデックス名（NULLなら使われていない）
-- possible_keys : 使える可能性があったインデックス（NULLなら選択肢自体がない）
--
-- Extra の代表的な値
--   - Using where     : サーバー側で追加のフィルタを行った
--   - Using index     : インデックスだけで結果が作れた（テーブル本体を読んでいない = 高速）
--   - Using filesort  : ソートのために追加の並べ替え処理が発生した
--   - Using temporary : 一時テーブルを作成した（GROUP BY等で発生しやすい）
