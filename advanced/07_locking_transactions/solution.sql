-- ---- シナリオ1: 行ロック ----
-- 実測タイムスタンプの例:
--   [B] UPDATE発行          : 14:36:10.815
--   [B] UPDATE完了(ブロック解除): 14:36:13.825   <- 約3秒後
--   [A] ROLLBACK実行        : 14:36:13.823   <- ほぼ同時刻
--
-- AがコミットもロールバックもせずUPDATEでid=1の行ロックを保持している間、
-- Bが同じid=1に対するUPDATEを発行すると、Aがロックを解放するまで
-- Bの処理は完全に停止する（エラーにはならず、ただ待たされる）。
-- これがInnoDBの行ロック（正確には排他ロック/Xロック）の基本動作。


-- ---- シナリオ2: ギャップロック ----
-- 実測タイムスタンプの例:
--   [B] INSERT発行     : 14:37:15.568
--   [B] INSERT完了      : 14:37:18.595   <- 約3秒後(Aのロールバックとほぼ同時)
--
-- 対象範囲(2030-01-01〜2030-01-02)には実際のデータが1件もないのに、
-- BのINSERTはブロックされた。これは「SELECT ... FOR UPDATE」が
-- 該当するデータの行だけでなく、その"間"の空間（ギャップ）にも
-- ロックをかけるため。
--
-- なぜこの仕組みが必要か:
--   MySQLのデフォルトの分離レベルは REPEATABLE READ。
--   もしギャップロックがなければ、Aのトランザクション中に
--   Bが同じ範囲に新しい行をINSERTしてコミットしてしまい、
--   Aが同じSELECTをもう一度実行すると新しい行が見える
--   （ファントムリードと呼ばれる不整合）ことになる。
--   ギャップロックはこのファントムリードを防ぐための仕組み。


-- ---- シナリオ3: デッドロック ----
-- 実測結果:
--   [A] id=1をロック → OK
--   [B] id=2をロック → OK
--   [A] id=2を要求   → Bが保持中のためブロック
--   [B] id=1を要求   → Aが保持中のためブロック（ここで循環待ちが発生）
--   数秒後、[B]側で次のエラーが発生:
--     ERROR 1213 (40001): Deadlock found when trying to get lock; try restarting transaction
--   [A]側は直後にロックを取得できて処理続行 (A-got-2 が返る)
--
-- InnoDBは定期的にロック待ちのグラフを監視しており、循環待ち（デッドロック）を
-- 検知すると、一方のトランザクションを強制的にロールバックしてエラーを返す。
-- どちらが犠牲(victim)になるかは「ロールバックのコストが小さい方」が
-- 選ばれる（一般的には変更行数が少ないトランザクション）。
--
-- 実務での対策:
--   - 複数テーブル/複数行を更新するときは、常に同じ順序でロックを取得する
--     （例: 必ずidの昇順で更新する、というルールを徹底する）
--   - アプリケーション側でデッドロックエラー(1213)を検知したら
--     トランザクションをリトライする実装にしておく
--   - トランザクションはできるだけ短く保つ（ロック保持時間を減らす）
