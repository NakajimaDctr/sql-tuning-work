-- ============================================================
-- 課題B: 「商品レビュー一覧」機能
-- ============================================================
-- 要件: 特定の商品(product_id=500)のレビューを、レビュアー名付きで
--       新しい順に一覧表示したい。

EXPLAIN SELECT * FROM reviews r, users u
WHERE r.user_id = u.id AND r.product_id = 500
ORDER BY r.created_at DESC;

