-- ============================================================
-- 課題A: 「2024年6月に完了した注文」レポート
-- ============================================================
-- 要件: 2024年6月に完了(status='completed')した注文を、
--       注文者名付きで新しい順に一覧表示したい。

EXPLAIN SELECT * FROM orders o, users u
WHERE o.user_id = u.id
  AND YEAR(o.created_at) = 2024 AND MONTH(o.created_at) = 6
  AND o.status = 'completed'
ORDER BY o.created_at DESC;

-- 上記のEXPLAINを確認し、問題点を洗い出せ（ヒント: これまでのステージで
-- 学んだアンチパターンが複数含まれている）。
-- 達成基準: rows が数万件以下になり、Extraから "Using filesort" が消えること。

